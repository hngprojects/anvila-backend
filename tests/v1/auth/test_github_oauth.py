def _patch_github_calls(
    monkeypatch: pytest.MonkeyPatch,
    *,
    token_payload: dict | None = None,
    profile: dict | None = None,
    emails: list | None = None,
    exchange_raises: Exception | None = None,
    profile_raises: Exception | None = None,
    emails_raises: Exception | None = None,
) -> None:
    """Stub the three outbound GitHub HTTP calls inside the service module."""

    async def fake_exchange(code, *, transport=None):
        if exchange_raises is not None:
            raise exchange_raises
        return token_payload or {"access_token": "gho_test_access_token"}

    async def fake_profile(access_token, *, transport=None):
        if profile_raises is not None:
            raise profile_raises
        return profile or {}

    async def fake_emails(access_token, *, transport=None):
        if emails_raises is not None:
            raise emails_raises
        return emails or []

    monkeypatch.setattr(github_service, "exchange_github_code", fake_exchange)
    monkeypatch.setattr(github_service, "fetch_github_profile", fake_profile)
    monkeypatch.setattr(github_service, "fetch_github_verified_emails", fake_emails)


def _state_pair() -> tuple[str, dict]:
    """Return a (state, cookies) pair where state is a valid oauth_state JWT."""
    state = create_oauth_state_token()
    return state, {"oauth_state": state}


def _assert_state_cookie_cleared(resp: httpx.Response) -> None:
    """Assert the state cookie is gone from the response.

    On success paths FastAPI honors `response.delete_cookie`, emitting
    `oauth_state=` with `Max-Age=0`. On HTTPException paths the response is
    regenerated by FastAPI's exception handler, dropping the cookie header
    entirely — so an absent header is also acceptable evidence that no live
    state cookie was returned.
    """
    set_cookie = resp.headers.get("set-cookie", "")
    if "oauth_state=" not in set_cookie:
        # Header absent — cookie cannot be live.
        return
    # If header present, it must be a deletion (Max-Age=0 or empty value).
    assert ("Max-Age=0" in set_cookie) or ("max-age=0" in set_cookie), set_cookie


def _assert_no_refresh_cookie(resp: httpx.Response) -> None:
    assert "refresh_token=" not in resp.headers.get("set-cookie", "")


async def _make_user(
    db: AsyncSession,
    *,
    email: str,
    is_active: bool = True,
    github_subject: str | None = None,
    provider: UserProvider = UserProvider.EMAIL,
) -> User:
    user = User(
        email=email,
        password_hash="$argon2id$dummy" if provider == UserProvider.EMAIL else None,
        display_name="Existing",
        provider=provider,
        email_verified=True,
        is_active=is_active,
        github_subject=github_subject,
    )
    db.add(user)
    await db.flush()
    await db.commit()
    await db.refresh(user)
    return user


