async def test_callback_code_replay_second_call_502(
    client: AsyncClient, monkeypatch: pytest.MonkeyPatch
):
    """Second callback with the same code: provider rejects exchange, route surfaces 502."""
    from fastapi import HTTPException

    call_count = {"n": 0}

    async def fake_exchange(code, *, transport=None):
        call_count["n"] += 1
        if call_count["n"] == 1:
            return {"access_token": "gho_first"}
        raise HTTPException(502, "GitHub token exchange failed")

    async def fake_profile(access_token, *, transport=None):
        return {"id": 1212, "login": "replay"}

    async def fake_emails(access_token, *, transport=None):
        return [
            {"email": "replay@example.com", "primary": True, "verified": True}
        ]

    monkeypatch.setattr(github_service, "exchange_github_code", fake_exchange)
    monkeypatch.setattr(github_service, "fetch_github_profile", fake_profile)
    monkeypatch.setattr(github_service, "fetch_github_verified_emails", fake_emails)

    state, cookies = _state_pair()
    first = await client.get(
        f"{BASE}/github/callback",
        params={"code": "replay_code", "state": state},
        cookies=cookies,
        follow_redirects=False,
    )
    assert first.status_code == 302

    state2, cookies2 = _state_pair()
    second = await client.get(
        f"{BASE}/github/callback",
        params={"code": "replay_code", "state": state2},
        cookies=cookies2,
    )
    assert second.status_code == 502
    _assert_no_refresh_cookie(second)
    _assert_state_cookie_cleared(second)


