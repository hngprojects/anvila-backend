async def test_github_start_returns_307_and_state_cookie(client: AsyncClient):
    """GET /auth/github redirects to GitHub authorize with correct query params."""
    resp = await client.get(f"{BASE}/github", follow_redirects=False)
    assert resp.status_code == 307

    location = resp.headers.get("location", "")
    parsed = urlparse(location)
    assert parsed.scheme == "https"
    assert parsed.netloc == "github.com"
    assert parsed.path == "/login/oauth/authorize"
    query = parse_qs(parsed.query)
    assert query["client_id"] == ["test-github-client-id"]
    assert query["redirect_uri"] == [
        "http://localhost:8000/api/v1/auth/github/callback"
    ]
    assert "read:user" in query["scope"][0]
    assert "user:email" in query["scope"][0]
    assert query["state"][0]
    assert query["response_type"] == ["code"]

    set_cookie = resp.headers.get("set-cookie", "")
    assert "oauth_state=" in set_cookie


