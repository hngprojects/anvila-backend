async def test_callback_brand_new_user_creates_and_commits(
    client: AsyncClient, monkeypatch: pytest.MonkeyPatch
):
    """A first-time GitHub login creates the user row, commits, and returns LoginData."""
    _patch_github_calls(
        monkeypatch,
        token_payload={"access_token": "gho_a"},
        profile={"id": 1001, "login": "octocat", "name": "Octo Cat"},
        emails=[{"email": "octocat@example.com", "primary": True, "verified": True}],
    )

    state, cookies = _state_pair()
    resp = await client.get(
        f"{BASE}/github/callback",
        params={"code": "the_code", "state": state},
        cookies=cookies,
        follow_redirects=False,
    )

    assert resp.status_code == 302
    assert resp.headers["location"].startswith(
        f"{settings.FRONTEND_URL}/auth/oauth/callback?ott="
    )
    set_cookie = resp.headers.get("set-cookie", "")
    assert "refresh_token=" in set_cookie
    _assert_state_cookie_cleared(resp)

    # Persistence assertion: open a fresh AsyncSessionLocal() and re-read the user.
    async with AsyncSessionLocal() as fresh:
        result = await fresh.execute(
            select(User).where(User.email == "octocat@example.com")
        )
        persisted = result.scalar_one()
        assert persisted.provider == UserProvider.GITHUB
        assert persisted.github_subject == "1001"
        assert persisted.email_verified is True


async def test_callback_returning_user_revokes_previous_refresh_tokens(
    client: AsyncClient, monkeypatch: pytest.MonkeyPatch, db_session: AsyncSession
):
    """A returning GitHub user's prior refresh tokens are revoked (Q9 rotation)."""
    from datetime import UTC, datetime, timedelta

    user = await _make_user(
        db_session,
        email="returning@example.com",
        github_subject="2002",
        provider=UserProvider.GITHUB,
    )
    pre_existing = RefreshToken(
        token_hash="a" * 64,
        user_id=user.id,
        expires_at=datetime.now(UTC) + timedelta(days=7),
    )
    db_session.add(pre_existing)
    await db_session.commit()

    _patch_github_calls(
        monkeypatch,
        token_payload={"access_token": "gho_b"},
        profile={"id": 2002, "login": "returning"},
        emails=[{"email": "returning@example.com", "primary": True, "verified": True}],
    )

    state, cookies = _state_pair()
    resp = await client.get(
        f"{BASE}/github/callback",
        params={"code": "code_b", "state": state},
        cookies=cookies,
        follow_redirects=False,
    )

    assert resp.status_code == 302
    assert resp.headers["location"].startswith(
        f"{settings.FRONTEND_URL}/auth/oauth/callback?ott="
    )

    rows = (
        await db_session.execute(
            select(RefreshToken).where(RefreshToken.user_id == user.id)
        )
    ).scalars().all()
    # Pre-existing token revoked; freshly minted token still active.
    revoked = [r for r in rows if r.revoked]
    active = [r for r in rows if not r.revoked]
    assert len(revoked) == 1
    assert revoked[0].token_hash == "a" * 64
    assert len(active) == 1


